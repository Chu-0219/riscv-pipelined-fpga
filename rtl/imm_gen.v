`timescale 1ns / 1ps
//============================================================================
// imm_gen.v  --  RV32I Immediate Generator (立即数生成器)
//
// 功能：从 32 位指令中提取立即数，按格式重新拼接并符号扩展到 32 位。
//
// 设计说明：
//   本模块为「自解码」版本——直接读 inst[6:0] (opcode) 判断指令格式，
//   不需要外部控制单元送入格式选择信号。写完 decoder.v 后若要改成
//   由 ImmSrc[2:0] 外部选择，只需把 case 的判据换掉，是分钟级重构。
//
//   纯组合逻辑：无时钟、无复位。
//
// 五种格式的立即数位宽：
//   I 型  12 位有符号  范围 -2048 ~ +2047
//   S 型  12 位有符号  范围 -2048 ~ +2047   （被切成两段）
//   B 型  13 位有符号  范围 -4096 ~ +4094   （最低位恒为 0，四段且顺序打乱）
//   U 型  20 位无扩展  直接作为结果的高 20 位，低 12 位补 0
//   J 型  21 位有符号  范围 -1048576 ~ +1048574（最低位恒为 0，四段且顺序打乱）
//============================================================================

module imm_gen (
    input  wire [31:0] inst,   // 32 位指令
    output reg  [31:0] imm     // 符号扩展后的 32 位立即数
);

    //------------------------------------------------------------------------
    // opcode 常量定义
    // 用 localparam 而不是裸写二进制，是为了让 case 分支能自解释。
    //------------------------------------------------------------------------
    localparam OP_IMM = 7'b0010011;  // addi / andi / ori / slti / slli ...
    localparam LOAD   = 7'b0000011;  // lw / lh / lb / lhu / lbu
    localparam JALR   = 7'b1100111;  // jalr
    localparam STORE  = 7'b0100011;  // sw / sh / sb
    localparam BRANCH = 7'b1100011;  // beq / bne / blt / bge / bltu / bgeu
    localparam LUI    = 7'b0110111;  // lui
    localparam AUIPC  = 7'b0010111;  // auipc
    localparam JAL    = 7'b1101111;  // jal

    always @(*) begin
        case (inst[6:0])

            //================================================================
            // I 型：立即数完整地放在 inst[31:20]，没有被切开
            //
            //  31                    20 19    15 14   12 11     7 6        0
            // |      imm[11:0]        |  rs1   |funct3 |   rd    |  opcode  |
            //
            // {20{inst[31]}} 把符号位复制 20 份 → 20 + 12 = 32 位
            //================================================================
            OP_IMM, LOAD, JALR:
                imm = {{20{inst[31]}}, inst[31:20]};

            //================================================================
            // S 型：立即数被切成两段
            //
            //  31          25 24    20 19    15 14   12 11     7 6        0
            // |  imm[11:5]  |  rs2   |  rs1   |funct3 | imm[4:0]|  opcode  |
            //
            // 原因：store 不需要 rd，空出 [11:7]；而新增的 rs2 必须占住
            //       [24:20] 这个固定位置，把立即数挤了出去。
            //
            // ⚠ 两段顺序不能反：inst[31:25] 是高位段，必须写在左边。
            //   写反了照样能编译、位宽也对，但值全错。
            //
            // 20 + 7 + 5 = 32 位
            //================================================================
            STORE:
                imm = {{20{inst[31]}}, inst[31:25], inst[11:7]};

            //================================================================
            // B 型：13 位立即数被打散成四段，且顺序被打乱
            //
            //  31    30      25 24  20 19  15 14 12 11    8   7  6        0
            // |imm12|imm[10:5]| rs2  | rs1  |fun3 |imm[4:1]|imm11| opcode |
            //
            // 注意 inst[7] 装的是 imm[11]，它被单独拎出来插在中间——
            // 这是为了让 B 型的其余字段与 S 型对齐，硬件上能复用走线。
            //
            // ⚠ imm[0] 恒为 0（硬接 1'b0），不是从指令里取的。
            //   分支目标必然 2 字节对齐，所以最低位无需编码。
            //   少写这一位会导致整个立即数错位，症状表现为「分支跳到
            //   奇怪的地方」，很容易误查分支逻辑而查错方向。
            //
            // 19 + 1 + 1 + 6 + 4 + 1 = 32 位
            //================================================================
            BRANCH:
                imm = {{19{inst[31]}},   // 符号扩展 19 位
                       inst[31],          // imm[12] 符号位本体
                       inst[7],           // imm[11] ← 单独插入的一位
                       inst[30:25],       // imm[10:5]
                       inst[11:8],        // imm[4:1]
                       1'b0};             // imm[0] 恒 0

            //================================================================
            // U 型：与前面方向相反 —— 不做符号扩展
            //
            //  31                                  12 11     7 6        0
            // |            imm[31:12]                |   rd    |  opcode |
            //
            // 这 20 位「本来就在高位」，直接作为结果的高 20 位，
            // 低 12 位强制补 0（留给后续的 addi 填充）。
            //
            //   lui  x5, 0x12345   → x5 = 0x12345000
            //   addi x5, x5, 0x678 → x5 = 0x12345678
            //
            // ⚠ 这里一个 {20{...}} 都不该出现。
            //
            // 20 + 12 = 32 位
            //================================================================
            LUI, AUIPC:
                imm = {inst[31:12], 12'b0};

            //================================================================
            // J 型：21 位立即数被打散成四段，顺序同样被打乱
            //
            //  31    30        21   20    19        12 11   7 6        0
            // |imm20| imm[10:1] |imm11| imm[19:12] |  rd   |  opcode  |
            //
            // inst[20] 装的是 imm[11]，也是单独插入的一位。
            // 字段排布刻意与 U 型对齐（都是 inst[31:12] 一大块）。
            //
            // ⚠ imm[0] 同样恒为 0。
            //
            // 11 + 1 + 8 + 1 + 10 + 1 = 32 位
            //================================================================
            JAL:
                imm = {{11{inst[31]}},   // 符号扩展 11 位
                       inst[31],          // imm[20] 符号位本体
                       inst[19:12],       // imm[19:12]
                       inst[20],          // imm[11] ← 单独插入的一位
                       inst[30:21],       // imm[10:1]
                       1'b0};             // imm[0] 恒 0

            //================================================================
            // default：未识别的 opcode（含 R 型——R 型没有立即数）
            //
            // ⚠ 这个分支必须显式写出。组合 always 块中若存在某条路径没有
            //   给 imm 赋值，综合工具会推断出锁存器（latch），这是数字设计
            //   里的典型错误，仿真可能看不出来但综合后行为异常。
            //================================================================
            default:
                imm = 32'b0;

        endcase
    end

endmodule

//============================================================================
// 已知约定（后续集成时不要在这里困惑）：
//
// 移位指令 SLLI / SRLI / SRAI 属于 I 型，但立即数并非 12 位有效——
// inst[31:25] 处放的是 funct7，真正的移位量 shamt 只有 inst[24:20] 五位。
// 例如 SRAI 的 funct7 = 0100000，走 I 型符号扩展会得到一个带 0x400 的怪值。
//
// 本模块的处理方式：照常按 I 型输出，由 ALU 只取 imm[4:0] 作为移位量。
// 这是常见做法，但必须在两侧都写明，否则集成时会互相怀疑。
//============================================================================
