`timescale 1ns / 1ps
//============================================================================
// imm_gen_tb.v  --  imm_gen 的自检式 testbench
//
// 自检（self-checking）的含义：TB 自己算出期望值并与 DUT 输出比对，
// 打印 PASS/FAIL，而不是打印一堆波形数值让人肉眼核对。
//
// 测试向量说明：
//   下面每一条指令机器码都是按 RISC-V 规范手工编码的真实指令，
//   不是用「和 DUT 相同的拼接逻辑」反推出来的。
//   这一点很重要：如果用同一套切分逻辑去构造测试指令，一旦理解有误，
//   构造和检查会同时错、互相抵消，测试就成了照镜子。
//
// 用例设计原则：
//   ⚠ 不使用全 0、全 1、对称位模式作为唯一测试向量。
//     S 型如果把两段拼反了，用 imm = -1（全 1）测永远发现不了。
//     所以每种格式都包含一个「非对称位模式」用例。
//
//   每种格式覆盖：最大正值 / 最小负值 / -1 或负数 / 非对称随机值
//   B、J 额外断言 imm[0] === 0
//   U 额外断言低 12 位全 0
//============================================================================

module imm_gen_tb;

    reg  [31:0] inst;
    wire [31:0] imm;

    integer total;
    integer failed;

    // DUT 实例化（具名端口连接）
    imm_gen dut (
        .inst (inst),
        .imm  (imm)
    );

    //------------------------------------------------------------------------
    // 通用检查任务：送激励 → 等组合逻辑稳定 → 比对 → 计数 → 打印
    //------------------------------------------------------------------------
    task check;
        input [31:0] test_inst;
        input [31:0] expected;
        input [511:0] name;
        begin
            inst = test_inst;
            #1;                          // 组合逻辑，等 1ns 让输出稳定
            total = total + 1;
            if (imm === expected) begin  // 用 === 而非 ==，可区分 x/z
                $display("PASS | %0s", name);
            end else begin
                failed = failed + 1;
                $display("FAIL | %0s", name);
                $display("       inst = %h   expected = %h   got = %h",
                         test_inst, expected, imm);
            end
        end
    endtask

    //------------------------------------------------------------------------
    // 专项断言：B/J 型立即数最低位必须为 0
    //------------------------------------------------------------------------
    task check_lsb_zero;
        input [31:0] test_inst;
        input [511:0] name;
        begin
            inst = test_inst;
            #1;
            total = total + 1;
            if (imm[0] === 1'b0) begin
                $display("PASS | %0s", name);
            end else begin
                failed = failed + 1;
                $display("FAIL | %0s  ->  imm[0] = %b, 应为 0", name, imm[0]);
            end
        end
    endtask

    //------------------------------------------------------------------------
    // 专项断言：U 型立即数低 12 位必须全 0
    //------------------------------------------------------------------------
    task check_low12_zero;
        input [31:0] test_inst;
        input [511:0] name;
        begin
            inst = test_inst;
            #1;
            total = total + 1;
            if (imm[11:0] === 12'b0) begin
                $display("PASS | %0s", name);
            end else begin
                failed = failed + 1;
                $display("FAIL | %0s  ->  imm[11:0] = %h, 应为 000", name, imm[11:0]);
            end
        end
    endtask


    initial begin
        total  = 0;
        failed = 0;

        $display("");
        $display("========================================================");
        $display("  imm_gen self-checking testbench");
        $display("========================================================");

        //====================================================================
        // I 型   addi rd, rs1, imm      opcode = 0010011
        //====================================================================
        $display("");
        $display("---- I-type ----");

        // addi x5, x6, 100        非对称检查基准
        check(32'h06430293, 32'h00000064, "I: addi x5,x6,100        -> +100");

        // addi x1, x2, 2047       最大正值
        check(32'h7FF10093, 32'h000007FF, "I: addi x1,x2,2047       -> +2047 (max)");

        // addi x5, x6, -2048      最小负值，验证符号扩展
        check(32'h80030293, 32'hFFFFF800, "I: addi x5,x6,-2048      -> -2048 (min)");

        // addi x1, x2, -1         高位应全 1
        check(32'hFFF10093, 32'hFFFFFFFF, "I: addi x1,x2,-1         -> -1");

        // addi x1, x2, 0x5A3      非对称位模式
        check(32'h5A310093, 32'h000005A3, "I: addi x1,x2,0x5A3      -> asymmetric");

        //====================================================================
        // S 型   sw rs2, imm(rs1)       opcode = 0100011
        // 关键：两段拼接顺序 inst[31:25] 在高、inst[11:7] 在低
        //====================================================================
        $display("");
        $display("---- S-type ----");

        // sw x7, 0x5A3(x9)        非对称：高段 0101101 / 低段 00011
        //                          两段拼反会立刻暴露
        check(32'h5A74A1A3, 32'h000005A3, "S: sw x7,0x5A3(x9)       -> asymmetric (段序检查)");

        // sw x7, 2047(x9)         最大正值
        check(32'h7E74AFA3, 32'h000007FF, "S: sw x7,2047(x9)        -> +2047 (max)");

        // sw x7, -2048(x9)        最小负值
        check(32'h8074A023, 32'hFFFFF800, "S: sw x7,-2048(x9)       -> -2048 (min)");

        // sw x7, -8(x9)           常见负偏移
        check(32'hFE74AC23, 32'hFFFFFFF8, "S: sw x7,-8(x9)          -> -8");

        //====================================================================
        // B 型   beq rs1, rs2, offset   opcode = 1100011
        // 关键：inst[7] 装 imm[11]，且 imm[0] 恒 0
        //====================================================================
        $display("");
        $display("---- B-type ----");

        // beq x1, x2, 100
        check(32'h06208263, 32'h00000064, "B: beq x1,x2,100         -> +100");

        // beq x1, x2, 4094        最大正值
        check(32'h7E208FE3, 32'h00000FFE, "B: beq x1,x2,4094        -> +4094 (max)");

        // beq x1, x2, -8          负偏移
        check(32'hFE208CE3, 32'hFFFFFFF8, "B: beq x1,x2,-8          -> -8");

        // 专项断言：最低位恒 0
        check_lsb_zero(32'h06208263, "B: imm[0] 恒零断言 (+100)");
        check_lsb_zero(32'hFE208CE3, "B: imm[0] 恒零断言 (-8)");

        //====================================================================
        // U 型   lui rd, imm20 / auipc rd, imm20
        // 关键：不做符号扩展，低 12 位补 0
        //====================================================================
        $display("");
        $display("---- U-type ----");

        // lui x5, 0x12345         非对称位模式
        check(32'h123452B7, 32'h12345000, "U: lui x5,0x12345        -> 0x12345000");

        // lui x5, 0xFFFFF         高位全 1：若误加符号扩展此条仍过，
        //                          但低 12 位若非全 0 会被下面的断言抓到
        check(32'hFFFFF2B7, 32'hFFFFF000, "U: lui x5,0xFFFFF        -> 0xFFFFF000");

        // auipc x5, 0x00001
        check(32'h00001297, 32'h00001000, "U: auipc x5,0x1          -> 0x00001000");

        // 专项断言：低 12 位全 0
        check_low12_zero(32'h123452B7, "U: 低 12 位全零断言 (lui)");
        check_low12_zero(32'h00001297, "U: 低 12 位全零断言 (auipc)");

        //====================================================================
        // J 型   jal rd, offset         opcode = 1101111
        // 关键：inst[20] 装 imm[11]，四段顺序被打乱，imm[0] 恒 0
        //====================================================================
        $display("");
        $display("---- J-type ----");

        // jal x1, 100
        check(32'h064000EF, 32'h00000064, "J: jal x1,100            -> +100");

        // jal x1, 0x1234          非对称位模式，专抓字段顺序错
        check(32'h234010EF, 32'h00001234, "J: jal x1,0x1234         -> asymmetric (段序检查)");

        // jal x1, -8              负偏移
        check(32'hFF9FF0EF, 32'hFFFFFFF8, "J: jal x1,-8             -> -8");

        // 专项断言：最低位恒 0
        check_lsb_zero(32'h064000EF, "J: imm[0] 恒零断言 (+100)");
        check_lsb_zero(32'hFF9FF0EF, "J: imm[0] 恒零断言 (-8)");

        //====================================================================
        // default 分支：未识别 opcode 应输出 0，且不得推断锁存器
        //====================================================================
        $display("");
        $display("---- default ----");

        check(32'h00000000, 32'h00000000, "D: 全零指令(非法)        -> imm = 0");
        check(32'h00C58533, 32'h00000000, "D: add x10,x11,x12 (R型) -> imm = 0");

        //====================================================================
        // 汇总
        //====================================================================
        $display("");
        $display("========================================================");
        $display("  TOTAL: %0d,  FAILED: %0d", total, failed);
        if (failed == 0)
            $display("  >>> ALL TESTS PASSED <<<");
        else
            $display("  >>> %0d TEST(S) FAILED <<<", failed);
        $display("========================================================");
        $display("");

        $finish;
    end

endmodule
